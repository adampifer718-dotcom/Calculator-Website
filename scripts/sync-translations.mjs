/**
 * Regenerates src/calculators/<calc>/translations.ts from the translation
 * files present in src/calculators/<calc>/i18n/<locale>.ts, so translators
 * only add files and never edit shared wiring. Run after adding or removing
 * a translation: npm run i18n:sync
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ORDER = ["ur", "es", "fr", "de", "ar", "it", "pt", "nl"];
const root = path.join(import.meta.dirname, "..", "src", "calculators");

for (const name of readdirSync(root)) {
  const dir = path.join(root, name);
  const textFile = path.join(dir, "text", "en.ts");
  if (!existsSync(path.join(dir, "index.ts")) || !existsSync(textFile)) continue;
  const type = /export type (\w+Text)\b/.exec(readFileSync(textFile, "utf8"))?.[1];
  if (!type) throw new Error(`No text type in ${textFile}`);
  const i18nDir = path.join(dir, "i18n");
  const locales = existsSync(i18nDir) ? ORDER.filter((l) => existsSync(path.join(i18nDir, `${l}.ts`))) : [];
  const lines = [
    'import type { TranslationMap } from "@/calculators/framework/types";',
    `import type { ${type} } from "./text/en";`,
    ...locales.map((l) => `import ${l} from "./i18n/${l}";`),
    "",
    "/** Complete translations of this calculator. Generated by scripts/sync-translations.mjs from the files in ./i18n. */",
    `export const translations: TranslationMap<${type}> = {${locales.length ? ` ${locales.join(", ")} ` : ""}};`,
    "",
  ];
  const file = path.join(dir, "translations.ts");
  const next = lines.join("\n");
  if (!existsSync(file) || readFileSync(file, "utf8") !== next) writeFileSync(file, next);
}
